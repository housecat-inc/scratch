// Command lucidetags turns lucide-static's tags.json into the Go table the
// icon picker searches. It is run by hand when the vendored Lucide data is
// upgraded, from the ui module, with the tags read from a scratch directory so
// no tarball or package/ folder lands in the checkout:
//
//	dir=$(mktemp -d) && curl -sfL https://registry.npmjs.org/lucide-static/-/lucide-static-<version>.tgz | tar xz -C "$dir" package/tags.json
//	go run ./cmd/lucidetags -in "$dir/package/tags.json" -version <version> -out icons/internal/lucide/icon_tags.go
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"slices"
	"strings"
)

func main() {
	in := flag.String("in", "", "path to lucide-static tags.json")
	out := flag.String("out", "", "path of the Go file to write")
	version := flag.String("version", "", "lucide-static version the tags come from")
	flag.Parse()
	if *in == "" || *out == "" || *version == "" {
		flag.Usage()
		os.Exit(2)
	}
	if err := run(*in, *out, *version); err != nil {
		fmt.Fprintln(os.Stderr, "lucidetags:", err)
		os.Exit(1)
	}
}

func run(in, out, version string) error {
	raw, err := os.ReadFile(in)
	if err != nil {
		return err
	}
	var tags map[string][]string
	if err := json.Unmarshal(raw, &tags); err != nil {
		return err
	}
	src, err := generate(tags, version)
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o644)
}

// normalizeTag lowercases a tag and joins its words with hyphens, the same
// shape the picker gives a query, so a multi-word tag matches a multi-word
// query.
func normalizeTag(tag string) string {
	return strings.Join(strings.Fields(strings.ToLower(tag)), "-")
}

func generate(tags map[string][]string, version string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/lucidetags from lucide-static %s tags.json; DO NOT EDIT.\n\n", version)
	b.WriteString("package lucide\n\n")
	fmt.Fprintf(&b, "const TagsVersion = %q\n\n", version)
	b.WriteString("// internalTags maps an icon name to its space-separated search tags; a tag\n")
	b.WriteString("// of several words has them joined by hyphens.\n")
	b.WriteString("var internalTags = map[string]string{\n")
	names := make([]string, 0, len(tags))
	for name := range tags {
		names = append(names, name)
	}
	slices.Sort(names)
	for _, name := range names {
		var kept []string
		for _, tag := range tags[name] {
			tag = normalizeTag(tag)
			if tag != "" && !slices.Contains(kept, tag) {
				kept = append(kept, tag)
			}
		}
		if len(kept) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\t%q: %q,\n", name, strings.Join(kept, " "))
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
