import * as Arr from "effect/Array";
import type * as JsonSchema from "effect/JsonSchema";
import * as SchemaRepresentation from "effect/SchemaRepresentation";

// A Go type's JSON Schema under the name a script imports its Effect Schema
// by, as app/pkg/browserschemas writes it.
export interface GoType {
  readonly name: string;
  readonly schema: JsonSchema.JsonSchema;
}

// schemaModule prints the module that exports an Effect Schema, and its
// type, for each Go type that source lists. Effect prints a Schema on one
// line; each struct's properties go on lines of their own here, so a changed
// field reads as one changed line in a diff.
//
// The Go types reflect without $defs, and jsonschema-go refuses a recursive
// one, so a Schema here never refers to another; one that did would need its
// reference printed first.
export function schemaModule(source: string, types: Arr.NonEmptyReadonlyArray<GoType>): string {
  const schemas = SchemaRepresentation.fromJsonSchemaMultiDocument({
    definitions: {},
    dialect: "draft-2020-12",
    schemas: Arr.map(types, (type) => type.schema),
  });
  const code = SchemaRepresentation.toCodeDocument(
    SchemaRepresentation.toRepresentations(Arr.map(schemas, (schema) => schema.ast)),
  );
  if (
    Arr.isReadonlyArrayNonEmpty(code.references.nonRecursives) || Object.keys(code.references.recursives).length > 0
  ) {
    throw new Error("a Schema refers to another, which schemaModule doesn't print");
  }
  const imports = Arr.flatMap(
    code.artifacts,
    (artifact) => artifact._tag === "Import" ? [artifact.importDeclaration] : [],
  );
  const exports = Arr.flatMap(types, (type, i) => [
    "",
    `export const ${type.name} = ${structPerLine(code.codes[i].runtime)};`,
    `export type ${type.name} = typeof ${type.name}.Type;`,
  ]);
  return Arr.join([
    `// Code generated by ${source} and ui/tools/print_schemas.ts. DO NOT EDIT.`,
    "",
    'import * as Schema from "effect/Schema";',
    ...imports,
    ...exports,
    "",
  ], "\n");
}

const struct = "Schema.Struct(";

// structPerLine puts each property of every Schema.Struct in runtime on a
// line of its own, indented by how many structs hold it, with a trailing
// comma. Everything else stays as Effect printed it. Effect prints strings as
// JSON does, in double quotes, so a quote ends one only when no backslash
// escapes it.
function structPerLine(runtime: string): string {
  let out = "";
  const brackets: Array<boolean> = [];
  const newline = () => `\n${"  ".repeat(Arr.filter(brackets, Boolean).length)}`;
  for (let i = 0; i < runtime.length; i++) {
    const char = runtime[i];
    if (char === '"') {
      let end = i + 1;
      while (runtime[end] !== '"') end += runtime[end] === "\\" ? 2 : 1;
      out += runtime.slice(i, end + 1);
      i = end;
    } else if (char === "{" || char === "[" || char === "(") {
      const isStruct = char === "{" && out.endsWith(struct);
      brackets.push(isStruct);
      out += isStruct ? `{${newline()}` : char;
      if (isStruct) { while (runtime[i + 1] === " ") i++; }
    } else if (char === "}" && brackets.at(-1) === true) {
      brackets.pop();
      out = `${out.trimEnd()},${newline()}}`;
    } else if (char === "}" || char === "]" || char === ")") {
      brackets.pop();
      out += char;
    } else if (char === "," && brackets.at(-1) === true) {
      out += `,${newline()}`;
      while (runtime[i + 1] === " ") i++;
    } else {
      out += char;
    }
  }
  return out;
}
